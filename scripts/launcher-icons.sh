#!/usr/bin/env bash
# Generates an app's launcher icon variants (Colour, Light, Dark) from one glyph and one colour.
#
#   scripts/launcher-icons.sh <app> <RRGGBB>
#
# Input:  apps/<app>/src/main/res/drawable/ic_launcher_foreground.xml, a 108dp vector drawn in
#         white (it is also the monochrome layer for themed icons).
# Output: values/ic_launcher_colors.xml, drawable/ic_launcher_foreground_{light,dark}.xml and
#         mipmap-anydpi/ic_launcher{,_light,_dark}.xml. Re-run after changing the glyph or colour.
set -euo pipefail
app=$1
hex=${2#\#}
res="$(dirname "$0")/../apps/$app/src/main/res"
test -f "$res/drawable/ic_launcher_foreground.xml" || { echo "no glyph in $res/drawable" >&2; exit 1; }

hue() { awk -v hex="$1" 'BEGIN{r=strtonum("0x" substr(hex,1,2))/255;g=strtonum("0x" substr(hex,3,2))/255;b=strtonum("0x" substr(hex,5,2))/255;
  mx=r;if(g>mx)mx=g;if(b>mx)mx=b;mn=r;if(g<mn)mn=g;if(b<mn)mn=b;d=mx-mn;
  if(d==0)h=0;else if(mx==r)h=60*(((g-b)/d)%6);else if(mx==g)h=60*((b-r)/d+2);else h=60*((r-g)/d+4);if(h<0)h+=360;print h}'; }
hsv() { awk -v h="$1" -v s="$2" -v v="$3" 'BEGIN{c=v*s;hh=h/60;t=(hh%2)-1;if(t<0)t=-t;x=c*(1-t);m=v-c;
  if(hh<1){r=c;g=x;b=0}else if(hh<2){r=x;g=c;b=0}else if(hh<3){r=0;g=c;b=x}else if(hh<4){r=0;g=x;b=c}else if(hh<5){r=x;g=0;b=c}else{r=c;g=0;b=x};
  printf "#FF%02X%02X%02X", (r+m)*255+0.5,(g+m)*255+0.5,(b+m)*255+0.5}'; }

h=$(hue "$hex")
mkdir -p "$res/values" "$res/mipmap-anydpi"
rm -f "$res/values/ic_launcher_background.xml"
cat > "$res/values/ic_launcher_colors.xml" <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/launcher-icons.sh $app $hex. Launcher icon colours are the one place
     Tessera uses fixed colours; the monochrome layer covers themed icons. -->
<resources>
    <color name="ic_launcher_background">#FF$hex</color>
    <color name="ic_launcher_light_background">$(hsv "$h" 0.08 0.98)</color>
    <color name="ic_launcher_light_foreground">#FF$hex</color>
    <color name="ic_launcher_dark_background">$(hsv "$h" 0.30 0.14)</color>
    <color name="ic_launcher_dark_foreground">$(hsv "$h" 0.28 0.92)</color>
</resources>
XML

for v in light dark; do
  sed "s|<vector |<vector android:tint=\"@color/ic_launcher_${v}_foreground\" |" "$res/drawable/ic_launcher_foreground.xml" \
    | sed '1!b;/^<?xml/!s|^|<?xml version="1.0" encoding="utf-8"?>\n|' \
    | sed "2i <!-- Generated by scripts/launcher-icons.sh from ic_launcher_foreground.xml. -->" \
    > "$res/drawable/ic_launcher_foreground_$v.xml"
done

icon() { # name background foreground
  cat > "$res/mipmap-anydpi/$1.xml" <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/launcher-icons.sh. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/$2" />
    <foreground android:drawable="@drawable/$3" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
XML
}
icon ic_launcher ic_launcher_background ic_launcher_foreground
icon ic_launcher_light ic_launcher_light_background ic_launcher_foreground_light
icon ic_launcher_dark ic_launcher_dark_background ic_launcher_foreground_dark
echo "generated icons for $app (hue $h)"
